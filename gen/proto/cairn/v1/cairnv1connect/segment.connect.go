// Segments and segment efforts.
//
// A Segment is a named geographic path with a polyline. Cairn supports two
// sources:
//
//   * "strava" — mirrored read-only when activities are imported from
//     Strava. Each user holds their own copy (Strava's API binds segments
//     to the authenticated athlete). If two users on the same instance
//     star the same Strava segment, each has their own mirror.
//
//   * "cairn" — user-defined within Cairn. May be private (owner-only) or
//     shared instance-wide (any user on the instance can match efforts
//     against it). The owning user controls visibility.
//
// Segment matching runs on every activity import — irrespective of the
// activity's source — using PostGIS ST_DWithin to filter candidates and a
// Hausdorff-distance + direction check to confirm matches. Matched
// efforts are recorded in segment_efforts and trigger PR notifications
// when they beat the user's prior best.
//
// Records (fastest 5k, max 5min power, etc.) are NOT segment-scoped;
// see best efforts in activity.proto. Segment leaderboards are an
// instance-wide ranking of efforts against a shared segment.

