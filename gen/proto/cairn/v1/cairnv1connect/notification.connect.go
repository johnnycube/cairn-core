// Notifications.
//
// A NotificationEvent is something the system wants to tell the user about:
// a new PR, an expired Strava credential, a worker upgrade available, a
// rate-limit-sustained warning, etc. Each event has a stable type, a
// severity, and an i18n key for client-side localization.
//
// Channels are pluggable adapters:
//
//   * IN_APP — always on, persisted in the DB, delivered via server-stream
//     to live UIs. Read state tracked per-user.
//
//   * EMAIL — optional. Templates per event_type. Adapter selected by the
//     instance operator (SMTP / SES / Resend / Mailgun) via env config.
//
//   * WEBHOOK — user-defined endpoints. The Core POSTs a signed payload
//     to each registered URL. Useful for piping into Home Assistant,
//     IFTTT, Discord webhooks, etc.
//
//   * PUSH — Web Push (v2, may roll out later).
//
// Preferences are a per-user matrix: for each event_type × channel, the
// user enables/disables delivery. A severity threshold also applies per
// channel ("only WARN and ERROR via email").
//
// Coalescing: events sharing a dedup_key within a short window are merged.
// Example: 50 activities re-imported triggers a single bulk_import_completed
// event with count=50, not 50 separate notifications.

