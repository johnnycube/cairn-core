// Authentication, sessions, and external-account linking.
//
// Cairn supports three login methods simultaneously, each a first-class
// option on the login screen:
//
//   1. LOCAL — username + password. Argon2id hashed. WebAuthn may be
//      enabled as a second factor or as a primary credential (passwordless
//      passkey login).
//
//   2. OIDC — any number of configured providers (Authentik, Keycloak,
//      Google, GitHub, etc.). Configured by the admin via AdminService;
//      users pick from the list at login time. A user may link multiple
//      OIDC identities. No additional WebAuthn 2FA required (the provider
//      handles its own MFA).
//
//   3. WEBAUTHN passkey — discoverable credential flow, no username needed.
//      Resolves to the linked user.
//
// Sessions are server-side, stored in Postgres, identified by an opaque
// cookie (browser) or bearer token (CLI/programmatic). Personal Access
// Tokens (PATs) provide long-lived, named credentials for the CLI and
// for webhook recipients.
//
// External accounts are OAuth-connected provider accounts (Strava, Garmin,
// ...). One user can link multiple accounts of the same provider — each
// must register their own Strava API app since instance-shared apps were
// dropped in favor of per-user apps for rate-limit isolation and webhook
// ownership.

